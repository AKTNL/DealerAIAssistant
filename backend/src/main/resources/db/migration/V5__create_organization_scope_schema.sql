INSERT INTO auth_role_permissions (role_id, permission_key)
SELECT role.id, 'ORGANIZATION_READ'
FROM auth_roles role
WHERE role.role_key = 'ADMIN'
  AND NOT EXISTS (
      SELECT 1
      FROM auth_role_permissions permission
      WHERE permission.role_id = role.id
        AND permission.permission_key = 'ORGANIZATION_READ'
  );

