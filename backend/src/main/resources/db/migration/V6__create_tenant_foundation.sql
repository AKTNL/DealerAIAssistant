INSERT INTO tenant_memberships (
    tenant_id, user_id, enabled, created_at, updated_at, version
)
SELECT default_tenant.id, user_row.id, user_row.enabled, user_row.created_at, user_row.updated_at, 0
FROM auth_users user_row
JOIN tenants default_tenant ON default_tenant.tenant_key = 'default'
WHERE NOT EXISTS (
    SELECT 1
    FROM tenant_memberships membership
    WHERE membership.tenant_id = default_tenant.id AND membership.user_id = user_row.id
);

INSERT INTO tenant_membership_roles (membership_id, role_id)
SELECT membership.id, user_role.role_id
FROM tenant_memberships membership
JOIN auth_user_roles user_role ON user_role.user_id = membership.user_id
WHERE membership.tenant_id = (SELECT id FROM tenants WHERE tenant_key = 'default')
  AND NOT EXISTS (
      SELECT 1
      FROM tenant_membership_roles membership_role
      WHERE membership_role.membership_id = membership.id
        AND membership_role.role_id = user_role.role_id
  );

