CREATE TABLE tenants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_key VARCHAR(64) NOT NULL,
    display_name VARCHAR(128) NOT NULL,
    enabled BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL,
    CONSTRAINT uq_tenants_key UNIQUE (tenant_key)
);

INSERT INTO tenants (
    tenant_key, display_name, enabled, created_at, updated_at, version
) SELECT 'default', 'Default Tenant', TRUE, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, 0
WHERE NOT EXISTS (SELECT 1 FROM tenants WHERE tenant_key = 'default');

CREATE TABLE tenant_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    enabled BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL,
    CONSTRAINT uq_tenant_memberships_user_tenant UNIQUE (tenant_id, user_id),
    CONSTRAINT fk_tenant_memberships_tenant
        FOREIGN KEY (tenant_id) REFERENCES tenants (id),
    CONSTRAINT fk_tenant_memberships_user
        FOREIGN KEY (user_id) REFERENCES auth_users (id)
);

CREATE TABLE tenant_membership_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    membership_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    CONSTRAINT uq_tenant_membership_roles UNIQUE (membership_id, role_id),
    CONSTRAINT fk_tenant_membership_roles_membership
        FOREIGN KEY (membership_id) REFERENCES tenant_memberships (id),
    CONSTRAINT fk_tenant_membership_roles_role
        FOREIGN KEY (role_id) REFERENCES auth_roles (id)
);

CREATE TABLE tenant_model_configs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    base_url VARCHAR(512) NOT NULL,
    model_name VARCHAR(128) NOT NULL,
    allowed_hosts VARCHAR(1024) NOT NULL,
    secret_ciphertext VARCHAR(2048) NOT NULL,
    secret_version INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL,
    CONSTRAINT uq_tenant_model_configs_tenant UNIQUE (tenant_id),
    CONSTRAINT fk_tenant_model_configs_tenant
        FOREIGN KEY (tenant_id) REFERENCES tenants (id)
);

CREATE INDEX idx_tenant_model_configs_updated
    ON tenant_model_configs (tenant_id, updated_at);

